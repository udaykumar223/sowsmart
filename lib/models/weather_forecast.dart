/// Represents a daily weather forecast entry from Open-Meteo or cached forecast.
class DailyWeatherForecast {
  final DateTime date;
  final double precipitationSum;
  final int precipitationProbabilityMax;
  final double windSpeed10mMax;
  final double temperature2mMax;

  const DailyWeatherForecast({
    required this.date,
    required this.precipitationSum,
    required this.precipitationProbabilityMax,
    required this.windSpeed10mMax,
    required this.temperature2mMax,
  });

  factory DailyWeatherForecast.fromJson(Map<String, dynamic> json) {
    return DailyWeatherForecast(
      date: json['date'] != null
          ? DateTime.tryParse(json['date'].toString()) ?? DateTime.now()
          : DateTime.now(),
      precipitationSum: (json['precipitationSum'] as num?)?.toDouble() ?? 0.0,
      precipitationProbabilityMax:
          (json['precipitationProbabilityMax'] as num?)?.toInt() ?? 0,
      windSpeed10mMax: (json['windSpeed10mMax'] as num?)?.toDouble() ?? 0.0,
      temperature2mMax: (json['temperature2mMax'] as num?)?.toDouble() ?? 0.0,
    );
  }

  Map<String, dynamic> toMap() {
    return {
      'date': date.toIso8601String(),
      'precipitationSum': precipitationSum,
      'precipitationProbabilityMax': precipitationProbabilityMax,
      'windSpeed10mMax': windSpeed10mMax,
      'temperature2mMax': temperature2mMax,
    };
  }
}

/// Weather advice configuration thresholds.
class WeatherConfig {
  final double rainProbabilityThreshold;
  final double precipitationSumThresholdMm;
  final double windSpeedMaxKmH;
  final double sprayRainProbabilityThreshold;
  final double temperatureMaxThresholdC;

  const WeatherConfig({
    this.rainProbabilityThreshold = 60.0,
    this.precipitationSumThresholdMm = 5.0,
    this.windSpeedMaxKmH = 15.0,
    this.sprayRainProbabilityThreshold = 40.0,
    this.temperatureMaxThresholdC = 38.0,
  });

  factory WeatherConfig.fromJson(Map<String, dynamic> json) {
    final irr = json['irrigation'] as Map<String, dynamic>? ?? {};
    final spray = json['spray'] as Map<String, dynamic>? ?? {};
    final heat = json['heat'] as Map<String, dynamic>? ?? {};

    return WeatherConfig(
      rainProbabilityThreshold:
          (irr['rainProbabilityThreshold'] as num?)?.toDouble() ?? 60.0,
      precipitationSumThresholdMm:
          (irr['precipitationSumThresholdMm'] as num?)?.toDouble() ?? 5.0,
      windSpeedMaxKmH: (spray['windSpeedMaxKmH'] as num?)?.toDouble() ?? 15.0,
      sprayRainProbabilityThreshold:
          (spray['rainProbabilityThreshold'] as num?)?.toDouble() ?? 40.0,
      temperatureMaxThresholdC:
          (heat['temperatureMaxThresholdC'] as num?)?.toDouble() ?? 38.0,
    );
  }
}

/// Types of weather advice generated by WeatherAdvisor.
enum AdviceType {
  none,
  skipIrrigation,
  warnSpray,
  heatAlert,
}

/// Advice result returned by WeatherAdvisor.
class WeatherAdvice {
  final AdviceType type;
  final String title;
  final String message;
  final String disclaimer;
  final bool offerPostpone;

  const WeatherAdvice({
    required this.type,
    required this.title,
    required this.message,
    this.disclaimer = 'Guidance only. Confirm with local field conditions.',
    this.offerPostpone = false,
  });

  static const WeatherAdvice none = WeatherAdvice(
    type: AdviceType.none,
    title: '',
    message: '',
  );
}
